# Masking: where a line is not prose


class Masker:
    """Spans of a line that are never references; carries multi-line comment state."""

    def __init__(self) -> None:
        self.in_comment = False

    def spans(self, line: str) -> list[tuple[int, int]]:
        out: list[tuple[int, int]] = []
        pos = 0
        if self.in_comment:
            end = line.find("-->")
            if end < 0:
                return [(0, len(line))]
            out.append((0, end + 3))
            pos = end + 3
            self.in_comment = False
        while True:
            start = line.find("<!--", pos)
            if start < 0:
                break
            end = line.find("-->", start + 4)
            if end < 0:
                out.append((start, len(line)))
                self.in_comment = True
                break
            out.append((start, end + 3))
            pos = end + 3
        for regex in (CODE_SPAN_RE, LINK_INLINE_RE, LINK_REF_RE, AUTOLINK_RE, URL_RE):
            out.extend((m.start(), m.end()) for m in regex.finditer(line))
        if DEFINITION_RE.match(line):
            out.append((0, len(line)))
        return out


