def sort_key(ident: str) -> tuple[str, list[int]]:
    ident = ident.rpartition(":")[2]  # a unit's <unit>:D<n> sorts by its D<n>
    return re.sub(r"[^A-Z]", "", ident), [int(n) for n in re.findall(r"\d+", ident)]


def relative_link(target: str, citing: str, line: int) -> str:
    start = str(Path(citing).parent)
    rel = os.path.relpath(target, start)
    return f"{quote(Path(rel).as_posix(), safe='/')}#L{line}"


def new_bolt(path: str) -> Bolt:
    root = Path(path)
    if not root.is_dir():
        raise FileNotFoundError(f"{root}: bolt folder not found")
    bolt = Bolt(root)
    bolt.load()
    return bolt


def emit(data: Any) -> None:
    sys.stdout.write(json.dumps(data, indent=2, ensure_ascii=False) + "\n")


def write_line(text: str) -> None:
    sys.stdout.write(text + "\n")


def section_end(bolt: Bolt, decl: Decl, full: bool = False) -> int:
    """The last line (1-based) of a declaration: its row, or its heading's section. The
    section is cut at 40 lines for display; ``full`` follows it to the next heading."""
    if decl.kind == "row":
        return decl.line
    lines = bolt.files[decl.file].lines
    last, fence = decl.line, False
    for line in lines[decl.line :]:
        if FENCE_RE.match(line):
            fence = not fence
        heading = None if fence else HEADING_RE.match(line)
        if heading and len(heading.group(1)) <= decl.level:
            break
        last += 1
        if not full and last - decl.line + 1 >= 40:
            break
    return last


def section(bolt: Bolt, decl: Decl, full: bool = False) -> str:
    lines = bolt.files[decl.file].lines
    return "\n".join(lines[decl.line - 1 : section_end(bolt, decl, full)]).rstrip("\n")


def cited_in(bolt: Bolt, decl: Decl) -> list[str]:
    """The declared ids cited inside one declaration, as the keys of ``bolt.winners``."""
    last = section_end(bolt, decl, True)
    found: list[str] = []
    for ref in bolt.file_refs.get(decl.file, []):
        if ref.kind == "id" and decl.line <= ref.line <= last:
            target = bolt.winner(ref.ident, decl.file)
            if target is not None and target.ident not in found:
                found.append(target.ident)
    return found


