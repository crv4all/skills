def table_cell(text: str) -> str:
    return text.replace("|", "\\|")


def cmd_index(args: argparse.Namespace) -> int:
    bolt = new_bolt(args.bolt)
    out = Path(args.out) if args.out else bolt.root / GENERATED_NAME
    groups: dict[str, list[str]] = {}
    for ident in bolt.winners:
        groups.setdefault(sort_key(ident)[0], []).append(ident)
    lines = [f"<!-- {INDEX_MARK}; do not edit -->", "", "# Id index", ""]
    here = str(out.resolve().parent)
    for prefix in sorted(groups):
        lines += [f"## {prefix}", "", "| Id | What | Declared in | Cited in |", "|---|---|---|---|"]
        for ident in sorted(groups[prefix], key=sort_key):
            decl = bolt.winners[ident]
            base = os.path.relpath(str((bolt.root / decl.file).resolve()), here)
            dest = f"{quote(Path(base).as_posix(), safe='/')}#L{decl.line}"
            count, files = bolt.cited(ident)
            shown = ", ".join(files[:5]) + (f" +{len(files) - 5}" if len(files) > 5 else "")
            cited = f"{count} ({shown})" if count else "0"
            lines.append(
                f"| {ident} | {table_cell(decl.gloss)} | [{decl.where()}]({dest}) | "
                f"{table_cell(cited)} |"
            )
        lines.append("")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines).rstrip("\n") + "\n", encoding="utf-8")
    emit(
        {
            "out": str(out),
            "config": bolt.config_found,
            "ids": len(bolt.winners),
            "prefixes": {p: len(groups[p]) for p in sorted(groups)},
        }
    )
    return EXIT_OK


