"""Make every id in a bolt resolvable without reading the files that declare it.

Bolt artifacts cite ids everywhere (``D10``, ``A-Q3``, ``FR-2``, ``L986``).
People and agents forget what an id stands for and re-read whole files to
recall it. This script resolves ids with no model tokens: ``show`` answers an
agent in one line per id, ``link`` turns each cited id into a Markdown link so a
person can click through, and ``index`` writes one page listing every id.

An id is declared where it starts a heading or the first cell of a table row
(outside fenced code, the same rule as ``check_traceability.py``); every other
occurrence is a reference. Ids are written bare in the artifacts: ``link`` adds
the brackets and one generated definition block at the end of each file, and
``link --remove`` takes them away again.
"""

