# Declarations


def strip_markup(text: str) -> str:
    text = re.sub(r"!?\[([^\]]*)\]\([^)]*\)", r"\1", text)
    text = re.sub(r"!?\[([^\]]*)\]\[[^\]]*\]", r"\1", text)
    text = re.sub(r"\[([^\]]*)\]", r"\1", text)
    text = text.replace("`", "").replace("*", "")
    text = re.sub(r"(?<!\w)_+|_+(?!\w)", "", text)
    return re.sub(r"\s+", " ", text).strip()


def cut(text: str, limit: int) -> str:
    if len(text) <= limit:
        return text
    head = text[: limit - 1]
    if text[limit - 1] != " " and " " in head:
        head = head[: head.rindex(" ")]
    return head.rstrip(" ,;:.-\u2013") + "\u2026"


def heading_gloss(rest: str) -> str:
    rest = re.sub(r"^[\s:\-\u2013]+", "", rest)
    return cut(strip_markup(rest), 90)


def row_gloss(cells: list[str], headers: list[str]) -> str:
    names = [strip_markup(h).lower() for h in headers]
    chosen: Optional[str] = None
    for group in (PRIMARY_COLUMNS, SECONDARY_COLUMNS):
        for column in group:
            if column in names:
                at = names.index(column)
                if 1 <= at < len(cells) and cells[at].strip():
                    chosen = cells[at]
                    break
        if chosen is not None:
            break
    if chosen is None:
        for cell in cells[1:]:
            if len(strip_markup(cell).split()) >= 3:
                chosen = cell
                break
    if chosen is None:
        return ""
    stripped = re.sub(r"^\s*\([^)]*\)\s*", "", chosen)
    text = strip_markup(stripped or chosen)
    text = re.split(r"(?<=[.!?])\s+", text, maxsplit=1)[0]
    return cut(text, 90)


def split_row(line: str) -> list[str]:
    body = line.strip()
    body = body[1:] if body.startswith("|") else body
    body = body[:-1] if body.endswith("|") and not body.endswith("\\|") else body
    return [c.strip() for c in re.split(r"(?<!\\)\|", body)]


def split_block(lines: list[str]) -> tuple[list[str], list[str]]:
    """Return ``(body lines, block lines)``; the blank line before the block is dropped."""
    start = next((i for i, ln in enumerate(lines) if ln.startswith("<!-- aidlc-refs:begin")), -1)
    if start < 0:
        return lines, []
    end = next(
        (i for i in range(start, len(lines)) if "aidlc-refs:end" in lines[i]), len(lines) - 1
    )
    body = lines[:start]
    if body and body[-1] == "":
        body = body[:-1]
    return body, lines[start : end + 1]


def block_labels(block: list[str]) -> list[str]:
    found = (re.match(r"^\[([^\]]+)\]:", line) for line in block)
    return [m.group(1) for m in found if m]


def unbracket(lines: list[str], labels: list[str]) -> tuple[list[str], int]:
    """Undo ``[LABEL]`` outside code, comments, fences and headings for ``labels``."""
    if not labels:
        return lines, 0
    suffixed = [x for x in labels if "@" in x]
    plain = [x for x in labels if "@" not in x]
    alternatives = []
    if suffixed:
        both = "|".join(re.escape(x) for x in suffixed)
        alternatives.append(rf"(?P<s>\[[^\[\]]+\]\[(?:{both})\])")
    if plain:
        alternatives.append(r"\[(?P<p>" + "|".join(re.escape(x) for x in plain) + r")\](?![(\[:])")
    pattern = re.compile("|".join(alternatives))
    out: list[str] = []
    count = 0
    in_fence = in_front = False
    mask = Masker()
    for index, line in enumerate(lines):
        if index == 0 and line.strip() == "---":
            in_front = True
            out.append(line)
            continue
        if in_front:
            in_front = line.strip() not in ("---", "...")
            out.append(line)
            continue
        if FENCE_RE.match(line):
            in_fence = not in_fence
            out.append(line)
            continue
        spans = mask.spans(line)
        if in_fence or HEADING_RE.match(line):
            out.append(line)
            continue
        parts: list[str] = []
        pos = 0
        for m in pattern.finditer(line):
            suffix = m.group("s") if "s" in pattern.groupindex else None
            if any(
                a <= m.start() < b and (suffix is None or (a, b) != (m.start(), m.end()))
                for a, b in spans
            ):
                continue
            parts.append(line[pos : m.start()])
            parts.append(suffix[1 : suffix.index("]")] if suffix else m.group("p"))
            pos = m.end()
            count += 1
        parts.append(line[pos:])
        out.append("".join(parts))
    return out, count


def parse_file(rel: str, raw: str) -> FileScan:
    body, block = split_block(raw.split("\n"))
    restored = 0
    text = raw
    if block:
        body, restored = unbracket(body, block_labels(block))
        text = "\n".join(body) + "\n"
    scan = FileScan(rel, raw, text.split("\n"), bool(block), restored)
    scan.opted_out = bool(OFF_RE.search(text))
    comment = LINES_COMMENT_RE.search(text)
    if comment:
        scan.lines_comment = comment.group(1)
    parse_declarations(scan)
    return scan


def id_cells(line: str, headers: list[str]) -> tuple[int, ...]:
    """Offsets of ids that are the whole content of a cell under an ``Id`` header.

    Such a cell names its row; it is not a citation, wherever the column sits."""
    columns = [i for i, h in enumerate(headers) if strip_markup(h).lower() == "id"]
    if not columns:
        return ()
    start = line.index("|") + 1
    pieces: list[tuple[int, str]] = []
    for part in re.split(r"(?<!\\)\|", line[start:]):
        pieces.append((start, part))
        start += len(part) + 1
    found: list[int] = []
    for column in columns:
        if column < len(pieces):
            offset, text = pieces[column]
            if re.fullmatch(ID, strip_markup(text)):
                found.append(offset + ID_RE.search(text).start(1))  # type: ignore[union-attr]
    return tuple(found)


def parse_declarations(scan: FileScan) -> None:
    lines = scan.lines
    in_fence = in_front = False
    headers: list[str] = []
    mask = Masker()
    for index, line in enumerate(lines):
        number = index + 1
        if index == 0 and line.strip() == "---":
            in_front = True
            continue
        if in_front:
            in_front = line.strip() not in ("---", "...")
            continue
        if FENCE_RE.match(line):
            in_fence = not in_fence
            continue
        if in_fence:
            continue
        inside_comment = mask.in_comment
        mask.spans(line)  # keeps the multi-line comment state
        if inside_comment:
            continue
        heading = HEADING_RE.match(line)
        is_row = not heading and line.lstrip().startswith("|") and not SEPARATOR_RE.match(line)
        if not is_row and not SEPARATOR_RE.match(line):
            headers = []
        skips = id_cells(line, headers) if is_row else ()
        if heading:
            found = START_RE.match(heading.group(2))
            if found:
                gloss = heading_gloss(heading.group(2)[found.end(1) :])
                decl = Decl(
                    found.group(1), scan.rel, number, "heading", gloss, len(heading.group(1))
                )
                question = QUESTION_RE.match(decl.ident)
                if question:
                    scan.questions.setdefault(int(question.group(1)), decl)
                else:
                    scan.decls.append(decl)
            continue
        if is_row:
            nxt = lines[index + 1] if index + 1 < len(lines) else ""
            if SEPARATOR_RE.match(nxt) and not headers:
                headers = split_row(line)
                scan.ref_lines.append((index, -1, "", skips))
                continue
            offset = line.index("|") + 1
            first_cell = line[offset:].split("|", 1)[0]
            found = START_RE.match(first_cell)
            if found:
                cells = split_row(line)
                decl = Decl(found.group(1), scan.rel, number, "row", row_gloss(cells, headers))
                decl.cells = {
                    strip_markup(h).lower(): strip_markup(c) for h, c in zip(headers, cells)
                }
                if strip_markup(first_cell) != decl.ident:
                    decl.rank = 3
                elif headers and strip_markup(headers[0]).lower() == "id":
                    decl.rank = 1
                else:
                    decl.rank = 2
                if QUESTION_RE.match(decl.ident):
                    scan.ref_lines.append((index, -1, "", skips))
                else:
                    scan.decls.append(decl)
                    scan.ref_lines.append((index, offset + found.start(1), decl.ident, skips))
                continue
        scan.ref_lines.append((index, -1, "", skips))


