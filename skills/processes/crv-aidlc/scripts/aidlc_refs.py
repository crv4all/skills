def resolve_file_arg(bolt: Bolt, value: str) -> str:
    for candidate in (bolt.root / value, Path(value)):
        if candidate.is_file():
            try:
                return candidate.resolve().relative_to(bolt.root.resolve()).as_posix()
            except ValueError:
                break
    raise FileNotFoundError(f"{value}: not a file of this bolt")


def decl_entry(bolt: Bolt, decl: Decl, token: str, full: bool) -> dict[str, Any]:
    count, files = bolt.cited(token)
    entry: dict[str, Any] = {
        "id": token,
        "found": True,
        "file": decl.file,
        "line": decl.line,
        "kind": decl.kind,
        "gloss": decl.gloss,
        "cited": {"count": count, "files": files},
    }
    others = [d for d in bolt.decls.get(token, []) if d is not decl]
    if others:
        entry["also"] = [{"file": d.file, "line": d.line, "kind": d.kind} for d in others]
    if full:
        entry["full"] = section(bolt, decl)
    return entry


def not_found(token: str, why: str = "") -> list[dict[str, Any]]:
    message = f"{token} | unresolved: {why}" if why else f"{token} | not declared in this bolt"
    return [{"id": token, "found": False, "message": message}]


def show_one(
    bolt: Bolt, token: str, file: Optional[str], full: bool, source: Optional[str] = None
) -> list[dict[str, Any]]:
    answer = ANSWER_RE.fullmatch(token)
    if answer:
        decl, why = bolt.answer_target(answer.group(1), int(answer.group(2)))
        if not decl:
            return not_found(token, why)
        return [decl_entry(bolt, decl, f"{answer.group(1)}-Q{int(answer.group(2))}", full)]
    question = QUESTION_RE.match(token)
    if question:
        number = int(question.group(1))
        if file:
            decl = bolt.files[file].questions.get(number) if file in bolt.files else None
            return [decl_entry(bolt, decl, token, full)] if decl else not_found(token)
        scans = [s for _, s in sorted(bolt.files.items()) if number in s.questions]
        found = [decl_entry(bolt, s.questions[number], token, full) for s in scans]
        return found or not_found(token)
    line = LINE_RE.fullmatch(token)
    if line and token not in bolt.decls:
        comment = bolt.files[file].lines_comment if file and file in bolt.files else None
        why = ""
        if source is None:
            source, why = bolt.line_source(comment)
        if source is None:
            return not_found(token, why)
        lines = bolt.source_lines(source)
        first = int(line.group(1))
        last = int(line.group(2)) if line.group(2) else first
        if lines is None or first < 1 or first > len(lines):
            return not_found(token, f"not a line of {source}")
        text = "\n".join(lines[first - 1 : min(last, len(lines), first + 39)])
        return [
            {
                "id": token,
                "found": True,
                "kind": "line",
                "file": source,
                "line": first,
                "last": last,
                "text": text if full else lines[first - 1].strip(),
            }
        ]
    win = bolt.winner(token, file or "")
    return [decl_entry(bolt, win, win.ident, full)] if win else not_found(token)


def text_line(entry: dict[str, Any]) -> str:
    if not entry["found"]:
        return str(entry["message"])
    where = f"{entry['file']}:{entry['line']}"
    if entry.get("kind") == "line":
        first = str(entry["text"]).split("\n", 1)[0]
        return f"{entry['id']} | {where} | {cut(first, 160)}"
    cited = entry["cited"]
    plural = "file" if len(cited["files"]) == 1 else "files"
    return (
        f"{entry['id']} | {where} | {entry['gloss']} | "
        f"cited {cited['count']}x in {len(cited['files'])} {plural}"
    )


def cmd_show(args: argparse.Namespace) -> int:
    bolt = new_bolt(args.bolt)
    file = resolve_file_arg(bolt, args.file) if args.file else None
    source = args.source
    if source and not (bolt.root / source).is_file():
        named = bolt.alias_for(source)
        if named is None or named.path is None:
            why = named.why if named else "not a file or alias of this bolt"
            raise FileNotFoundError(f"{source}: {why}")
        source = named.path
    entries: list[dict[str, Any]] = []
    for token in args.ids:
        entries.extend(show_one(bolt, token, file, args.full, source))
    if args.format == "json":
        emit(entries)
    else:
        for entry in entries:
            write_line(text_line(entry))
            if args.full and entry["found"] and entry.get("full"):
                write_line(str(entry["full"]))
    return EXIT_OK if all(e["found"] for e in entries) else EXIT_FINDINGS


