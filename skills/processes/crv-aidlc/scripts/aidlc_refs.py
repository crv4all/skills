def definition_for(
    bolt: Bolt, ref: Ref, target: tuple[str, int], citing: str, titles: bool, label: str
) -> str:
    dest = relative_link(target[0], citing, target[1])
    title = ""
    if titles and ref.kind != "line":
        decl = bolt.winner(ref.ident, citing)
        if ref.kind == "answer":
            prefix, number = ref.ident.split("-Q")
            decl, _ = bolt.answer_target(prefix, int(number))
        if decl and decl.gloss:
            title = ' "' + cut(decl.gloss, 70).replace("\\", "\\\\").replace('"', '\\"') + '"'
    return f"[{label}]: {dest}{title}"


def digest_is_last(lines: list[str]) -> bool:
    last = ""
    fence = False
    for line in lines:
        if FENCE_RE.match(line):
            fence = not fence
        elif not fence and re.match(r"^#{1,6}\s", line):
            last = line
    return bool(re.match(r"^##\s+Digest\s*$", last))


def link_file(
    bolt: Bolt, scan: FileScan, with_lines: bool, remove: bool, titles: bool = False
) -> tuple[str, dict[str, int]]:
    """The new text of one file and its counts; the raw text when nothing changes."""
    stats = {"links_added": 0, "definitions": 0, "bytes_added": 0}
    restored_text = "\n".join(scan.lines)
    unchanged = scan.raw if not scan.had_block else restored_text
    refs = [r for r in bolt.file_refs.get(scan.rel, []) if with_lines or r.kind != "line"]
    if remove or not refs:
        return unchanged, stats
    if digest_is_last(scan.lines):
        # aidlc_state.py counts every line under "## Digest" up to the next heading, so a
        # block after a final digest would push it over its limit.
        bolt.digest_last.append(scan.rel)
        return unchanged, stats
    definitions: dict[str, str] = {}
    labels: dict[str, dict[tuple[str, int], str]] = {}  # token -> target -> label
    plan: list[tuple[Ref, str]] = []
    for ref in sorted(refs, key=lambda r: (r.line, r.start)):
        target, _ = bolt.resolve(ref, scan)
        if target is None:
            continue
        known = labels.setdefault(ref.token, {})
        if target not in known:
            label = ref.token
            if known:
                # One label, two targets: later targets get a full reference link.
                suffix = ref.alias or Path(target[0]).name
                label = f"{ref.token}@{suffix}"
                if label in known.values():
                    label = f"{ref.token}@{target[0]}"
            known[target] = label
        label = known[target]
        plan.append((ref, label))
        definitions[label] = definition_for(bolt, ref, target, scan.rel, titles, label)
    lines = list(scan.lines)
    for ref, label in reversed(plan):
        row = lines[ref.line - 1]
        written = f"[{ref.token}]" if label == ref.token else f"[{ref.token}][{label}]"
        lines[ref.line - 1] = f"{row[: ref.start]}{written}{row[ref.end :]}"
        stats["links_added"] += 1
    stats["links_added"] = max(0, stats["links_added"] - scan.restored)
    stats["definitions"] = len(definitions)
    ordered = sorted(
        definitions,
        key=lambda t: (sort_key(re.sub(r"[-\u2013]L?\d+$", "", t.split("@")[0])), t),
    )
    block = "\n".join([BLOCK_BEGIN, *[definitions[t] for t in ordered], BLOCK_END])
    return "\n".join(lines).rstrip("\n") + "\n\n" + block + "\n", stats


def cmd_link(args: argparse.Namespace) -> int:
    bolt = new_bolt(args.bolt)
    report: dict[str, Any] = {}
    diff: list[str] = []
    totals = {"files_changed": 0, "links_added": 0, "definitions": 0, "bytes_added": 0}
    for rel, scan in sorted(bolt.files.items()):
        new_text, stats = link_file(bolt, scan, args.lines, args.remove, args.titles)
        changed = new_text != scan.raw
        if changed:
            stats["bytes_added"] = len(new_text.encode("utf-8")) - len(scan.raw.encode("utf-8"))
            diff.extend(
                difflib.unified_diff(
                    scan.raw.splitlines(keepends=True),
                    new_text.splitlines(keepends=True),
                    fromfile=f"a/{rel}",
                    tofile=f"b/{rel}",
                )
            )
            totals["files_changed"] += 1
            if not args.dry_run:
                (bolt.root / rel).write_bytes(new_text.encode("utf-8"))
        if changed or stats["definitions"]:
            report[rel] = stats
        for key in ("links_added", "definitions", "bytes_added"):
            totals[key] += stats[key]
    if args.diff_out:
        Path(args.diff_out).write_text("".join(diff), encoding="utf-8")
    duplicates = [
        {
            "id": ident,
            "kept": f"{found[0].where()} ({found[0].kind})",
            "also": [f"{d.where()} ({d.kind})" for d in found[1:]],
        }
        for ident, found in sorted(bolt.decls.items(), key=lambda kv: sort_key(kv[0]))
        if len(found) > 1
    ]
    emit(
        {
            "dry_run": bool(args.dry_run),
            "config": bolt.config_found,
            "digest_last": sorted(bolt.digest_last),
            "opted_out": sorted(r for r, sc in bolt.files.items() if sc.opted_out),
            "files": report,
            "totals": totals,
            "unresolved": [] if args.remove else bolt.unresolved,
            "skipped_qualified": [
                {"id": s.ident, "file": s.file, "line": s.line, "qualifier": s.qualifier}
                for s in bolt.skipped
            ],
            "duplicates": duplicates,
        }
    )
    return EXIT_OK


