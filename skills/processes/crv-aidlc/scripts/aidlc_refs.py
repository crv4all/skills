DEFINITION_RE = re.compile(r"^\s{0,3}\[[^\]]+\]:.*$")
AUTOLINK_RE = re.compile(r"<[A-Za-z][^>\s]*>")
URL_RE = re.compile(r"(?:https?://|www\.)[^\s)>\]]+")


# --------------------------------------------------------------------------
# Data


@dataclass
class Decl:
    ident: str
    file: str
    line: int
    kind: str  # "heading" or "row"
    gloss: str
    level: int = 0
    rank: int = 0  # 0 heading, 1 exact row of an Id table, 2 exact row, 3 row that starts with it
    cells: dict[str, str] = field(default_factory=dict)  # a row's cells by lower-case header

    def where(self) -> str:
        return f"{self.file}:{self.line}"


@dataclass
class Alias:
    path: Optional[str]
    why: str
    key: str
    template: Optional[str] = None  # the wildcard target, e.g. "knowledge/repos/*.md"


@dataclass
class Ref:
    token: str
    ident: str
    kind: str  # "id", "answer" or "line"
    file: str
    line: int  # 1-based
    start: int
    end: int
    first: int = 0  # first line of a line ref
    sourced: bool = False  # an alias (or inheritance) named the line source
    source: Optional[str] = None
    source_why: str = ""
    alias: str = ""  # the alias key that named the source ("" for a wildcard or none)
    template: Optional[str] = None  # wildcard path template, for lists under "card *"


@dataclass
class Skipped:
    ident: str
    file: str
    line: int
    qualifier: str


@dataclass
class FileScan:
    rel: str
    raw: str  # the file as it is on disk
    lines: list[str]  # the file without our generated block and brackets
    had_block: bool = False
    restored: int = 0  # brackets taken off by reading the file
    decls: list[Decl] = field(default_factory=list)
    questions: dict[int, Decl] = field(default_factory=dict)
    # (line index, start of the declared token or -1, id the row declares or "")
    ref_lines: list[tuple[int, int, str, tuple[int, ...]]] = field(default_factory=list)
    lines_comment: Optional[str] = None
    opted_out: bool = False


class Bolt:
    def __init__(self, root: Path) -> None:
        self.root = root
        self.files: dict[str, FileScan] = {}
        self.decls: dict[str, list[Decl]] = {}
        self.winners: dict[str, Decl] = {}
        self.refs: dict[str, list[Ref]] = {}
        self.file_refs: dict[str, list[Ref]] = {}
        self.unresolved: list[dict[str, Any]] = []
        self.skipped: list[Skipped] = []
        self.unreadable: list[str] = []  # files skipped by ``load(skip_unreadable=True)``
        self.digest_last: list[str] = []
        self._outline: Optional[list[str]] = None
        self.config_found = False
        self.line_sources: dict[str, str] = {}
        self.units: list[str] = []  # unit ids of a split bolt: their decisions are <unit>:D<n>
        self.unit_re: Optional[re.Pattern[str]] = None
        self.foreign_re: Optional[re.Pattern[str]] = None
        self._aliases: list[tuple[re.Pattern[str], str, bool, str]] = []

    # -- config -----------------------------------------------------------

    def load_config(self) -> None:
        path = self.root / CONFIG_NAME
        if not path.is_file():
            return
        self.config_found = True
        try:
            data = json.loads(path.read_text(encoding="utf-8"))
        except (ValueError, OSError) as exc:
            raise ValueError(f"{path}: not valid JSON ({exc})") from exc
        if not isinstance(data, dict):
            raise ValueError(f"{path}: the top level must be an object")
        sources = data.get("line_sources", {})
        words = data.get("foreign_words", [])
        if not isinstance(sources, dict) or not all(
            isinstance(k, str) and isinstance(v, str) and k.strip() for k, v in sources.items()
        ):
            raise ValueError(f"{path}: line_sources must map alias strings to path strings")
        if not isinstance(words, list) or not all(isinstance(w, str) and w for w in words):
            raise ValueError(f"{path}: foreign_words must be a list of non-empty strings")
        for key in sources:
            parts = key.split()
            if "*" in "".join(parts[:-1]) or ("*" in parts[-1] and parts[-1] != "*"):
                raise ValueError(f"{path}: in {key!r} a * may only be the last word")
            if parts[-1] == "*" and len(parts) < 2:
                raise ValueError(f"{path}: the key {key!r} needs a word before the *")
        self.line_sources = dict(sources)
        for key, target in self.line_sources.items():
            parts = key.split()
            wild = parts[-1] == "*"
            head = r"\s+".join(re.escape(w) for w in (parts[:-1] if wild else parts))
            tail = rf"\s+({SLUG})$" if wild else "$"
            self._aliases.append((re.compile(rf"(?<![\w.-]){head}{tail}"), target, wild, key))
        if words:
            joined = "|".join(re.escape(w) for w in sorted(words, key=len, reverse=True))
            self.foreign_re = re.compile(rf"(?<![\w-])({joined}) $")

    def alias_for(self, text: str) -> Optional[Alias]:
        """The source an alias written at the end of ``text`` names."""
        text = text.rstrip(" \t(`")
        best: Optional[tuple[int, str, bool, str, str]] = None
        for pattern, target, wild, key in self._aliases:
            found = pattern.search(text)
            if not found:
                continue
            path = target.replace("*", found.group(1)) if wild else target
            size = found.end() - found.start()
            if best is None or size > best[0]:
                best = (size, path, wild, key, target)
        if best is None:
            return None
        _, path, wild, key, target = best
        template = target if wild else None
        label = "" if wild else key
        if not (self.root / path).is_file():
            return Alias(None, f"source file missing: {path}", label, template)
        return Alias(path, "", label, template)

    # -- loading ----------------------------------------------------------

    def load_units(self) -> None:
        """A split bolt names its units in state.json; others have no qualified ids."""
        try:
            state = json.loads((self.root / "state.json").read_text(encoding="utf-8"))
            if state.get("unit_state") == "split":
                self.units = [str(u["id"]) for u in state.get("units", [])]
        except (OSError, ValueError, AttributeError, KeyError, TypeError):
            return
        if self.units:
            names = "|".join(re.escape(u) for u in sorted(self.units, key=len, reverse=True))
            self.unit_re = re.compile(rf"(?<![\w-])(?:{names}):{ID}(?![\w-])")

    def unit_of(self, rel: str) -> Optional[str]:
        """The unit whose folder under ``docs/construction/`` holds ``rel``."""
        parts = Path(rel).parts
        if len(parts) > 3 and parts[:2] == ("docs", "construction") and parts[2] in self.units:
            return parts[2]
        return None

    def winner(self, ident: str, rel: str) -> Optional[Decl]:
        """The declaration of ``ident`` as cited from ``rel``: its own unit's first."""
        unit = self.unit_of(rel)
        return (unit and self.winners.get(f"{unit}:{ident}")) or self.winners.get(ident)

    def load(self, skip_unreadable: bool = False) -> None:
        """Parse every Markdown file. A file that is not UTF-8 stops the load, or with
        ``skip_unreadable`` is named in ``unreadable`` and left out."""
        self.load_config()
        self.load_units()
        for path in sorted(self.root.rglob("*.md")):
            rel = path.relative_to(self.root)
            if is_skipped(rel) or (rel.parts[0] == "units" and rel.name == "log.md"):
                continue
            try:
                raw = path.read_text(encoding="utf-8")
            except UnicodeDecodeError as exc:
                if not skip_unreadable:
                    raise ValueError(f"{path}: not valid UTF-8 text ({exc.reason})") from exc
                self.unreadable.append(rel.as_posix())
                LOG.warning("%s: not valid UTF-8 text, left out of the ids", rel.as_posix())
                continue
            if rel.name == GENERATED_NAME or INDEX_MARK in raw.split("\n", 1)[0]:
                continue
            if rel == Path("log.md"):
                continue  # the bolt's state log is written by aidlc_state.py
            posix = rel.as_posix()
            self.files[posix] = parse_file(posix, raw)
        for scan in self.files.values():
            unit = self.unit_of(scan.rel)
            for decl in scan.decls:
                if unit:
                    decl.ident = f"{unit}:{decl.ident}"
                self.decls.setdefault(decl.ident, []).append(decl)
        for ident, found in self.decls.items():
            found.sort(key=lambda d: (d.rank, d.file, d.line))
            self.winners[ident] = found[0]
        for scan in self.files.values():
            if not scan.opted_out:
                self.collect_refs(scan)

    # -- line source ------------------------------------------------------

    def outline_sources(self) -> list[str]:
        if self._outline is None:
            found: list[str] = []
            path = self.root / OUTLINE
            if path.is_file():
                try:
                    data = json.loads(path.read_text(encoding="utf-8"))
                    for item in data.get("files", []):
                        name = str(item.get("path", ""))
                        if name.endswith(".md"):
                            found.append(name)
                except (ValueError, OSError, AttributeError) as exc:
                    LOG.warning("%s: unreadable (%s)", path, exc)
            self._outline = found
        return self._outline

    def line_source(self, comment: Optional[str]) -> tuple[Optional[str], str]:
        """The file a line ref resolves to, or ``(None, reason)``."""
        if comment:
            named = self.alias_for(comment)
            if named is None:
                return comment, ""
            return (named.path, named.why)
        sources = self.outline_sources()
        if len(sources) == 1:
            return sources[0], ""
        if not sources:
            return None, "no line source (knowledge/_outline.json lists no .md file)"
        return None, "several line sources and no <!-- aidlc-lines: path --> comment"

    def source_lines(self, rel: str) -> Optional[list[str]]:
        try:
            return (self.root / rel).read_text(encoding="utf-8").split("\n")
        except (OSError, UnicodeDecodeError):
            return None

    # -- references -------------------------------------------------------

    def answer_target(self, prefix: str, number: int) -> tuple[Optional[Decl], str]:
        pattern = ANSWER_FILES.get(prefix)
        if pattern is None:
            return None, f"unknown answer prefix {prefix}"
        candidates = sorted(
            rel for rel in self.files if fnmatch.fnmatchcase(Path(rel).name, pattern)
        )
        if not candidates:
            return None, f"no file {pattern} in the bolt"
        found = [
            self.files[rel].questions[number]
            for rel in candidates
            if number in self.files[rel].questions
        ]
        if len(found) == 1:
            return found[0], ""
        if not found:
            return None, f"no heading Q{number} in {pattern}"
        exact = [d for d in found if Path(d.file).name == pattern.replace("*", "")]
        if len(exact) == 1:
            return exact[0], ""
        names = ", ".join(d.file for d in found)
        return None, f"heading Q{number} is in several files: {names}"

    def resolve(self, ref: Ref, scan: FileScan) -> tuple[Optional[tuple[str, int]], str]:
        """Return ``((file, line), "")`` or ``(None, reason)``."""
        if ref.kind == "id":
            win = self.winner(ref.ident, scan.rel)
            return ((win.file, win.line), "") if win else (None, "not declared")
        if ref.kind == "answer":
            prefix, number = ref.ident.split("-Q")
            decl, why = self.answer_target(prefix, int(number))
            return ((decl.file, decl.line), "") if decl else (None, why)
        if ref.sourced:
            source, why = ref.source, ref.source_why
        else:
            source, why = self.line_source(scan.lines_comment)
        if source is None:
            return None, why
        lines = self.source_lines(source)
        if lines is None:
            return None, f"line source {source} cannot be read"
        if ref.first < 1 or ref.first > len(lines):
            return None, f"{source} has {len(lines)} lines"
        return (source, ref.first), ""

    def collect_refs(self, scan: FileScan) -> None:
        shapes = {
            (re.sub(r"[^A-Z]", "", i), "-" in i) for i in (k.rpartition(":")[2] for k in self.decls)
        }
        for index, declared_at, own, skips in scan.ref_lines:
            line = scan.lines[index]
            spans = Masker().spans(line)
            taken: list[tuple[int, int]] = []
            found: list[Ref] = []

            def free(start: int, end: int, spans=spans, taken=taken) -> bool:
                return not any(a < end and start < b for a, b in spans + taken)

            def keep(ref: Ref, taken=taken, found=found) -> None:
                taken.append((ref.start, ref.end))
                found.append(ref)

            for m in ANSWER_RE.finditer(line):
                if free(m.start(), m.end()):
                    ident = f"{m.group(1)}-Q{int(m.group(2))}"
                    keep(Ref(m.group(0), ident, "answer", scan.rel, index + 1, m.start(), m.end()))
            previous: Optional[Ref] = None
            for m in LINE_RE.finditer(line):
                if not free(m.start(), m.end()):
                    continue
                if m.group(2) is None and f"L{m.group(1)}" in self.decls:
                    continue
                named = self.alias_for(line[: m.start()])
                sourced, source, why, alias, template = False, None, "", "", None
                if named is not None:
                    sourced, source, why = True, named.path, named.why
                    alias, template = named.key, named.template
                elif previous is not None and previous.sourced:
                    slug = None
                    if previous.template:
                        slug = SLUG_LIST_RE.match(line[previous.end : m.start()])
                    if slug and slug.group(1) not in ("and", "to"):
                        path = previous.template.replace("*", slug.group(1))  # type: ignore[union-attr]
                        sourced, template = True, previous.template
                        source = path if (self.root / path).is_file() else None
                        why = "" if source else f"source file missing: {path}"
                    elif only_glue(line[previous.end : m.start()]):
                        sourced, source, why = True, previous.source, previous.source_why
                        alias, template = previous.alias, previous.template
                if not sourced and FILE_TOKEN_RE.search(line[max(0, m.start() - 60) : m.start()]):
                    taken.append((m.start(), m.end()))
                    previous = None
                    continue
                token = m.group(0)
                previous = Ref(
                    token,
                    token,
                    "line",
                    scan.rel,
                    index + 1,
                    m.start(),
                    m.end(),
                    int(m.group(1)),
                    sourced,
                    source,
                    why,
                    alias,
                    template,
                )
                keep(previous)
            for m in self.unit_re.finditer(line) if self.unit_re else []:
                if free(m.start(), m.end()):
                    keep(Ref(m.group(0), m.group(0), "id", scan.rel, index + 1, m.start(), m.end()))
            for m in ID_RE.finditer(line):
                ident = m.group(1)
                if not free(m.start(1), m.end(1)) or m.start(1) in (declared_at, *skips):
                    continue
                if QUESTION_RE.match(ident) or ident == own:
                    continue
                keep(Ref(ident, ident, "id", scan.rel, index + 1, m.start(1), m.end(1)))
            foreign: Optional[tuple[Ref, str]] = None
            for ref in sorted(found, key=lambda r: r.start):
                before = line[ref.start - 1] if ref.start > 0 else ""
                after = line[ref.end] if ref.end < len(line) else ""
                qualifier = None if ref.sourced else QUALIFIER_RE.search(line[: ref.start])
                if ref.kind == "id" and self.foreign_re is not None:
                    word = self.foreign_re.search(line[: ref.start])
                    if word:
                        foreign = (ref, word.group(1))
                    elif foreign is not None and only_list_glue(line[foreign[0].end : ref.start]):
                        foreign = (ref, foreign[1])
                    else:
                        foreign = None
                    if foreign is not None:
                        self.skipped.append(Skipped(ref.token, scan.rel, ref.line, foreign[1]))
                        continue
                elif ref.kind != "id":
                    foreign = None
                if qualifier:
                    self.skipped.append(
                        Skipped(ref.token, scan.rel, ref.line, qualifier.group(0).strip())
                    )
                    continue
                if (before and before in ":/#[") or (after and after in "([:]"):
                    continue
                target, why = self.resolve(ref, scan)
                if target is None:
                    bare = ref.ident.rpartition(":")[2]
                    shape = (re.sub(r"[^A-Z]", "", bare), "-" in bare)
                    if ref.kind == "id" and shape not in shapes:
                        continue  # "SHA256", "C08": not an id of this bolt
                    self.unresolved.append(
                        {"id": ref.token, "file": scan.rel, "line": ref.line, "reason": why}
                    )
                    continue
                key = ref.token if ref.kind == "line" else ref.ident
                unit = self.unit_of(scan.rel)
                if ref.kind == "id" and unit and f"{unit}:{ref.ident}" in self.winners:
                    key = f"{unit}:{ref.ident}"
                self.refs.setdefault(key, []).append(ref)
                self.file_refs.setdefault(scan.rel, []).append(ref)

    def cited(self, ident: str) -> tuple[int, list[str]]:
        refs = self.refs.get(ident, [])
        return len(refs), sorted({r.file for r in refs})


def only_glue(text: str) -> bool:
    """Between two line refs: separators, short parentheticals and id-like tokens only."""
    for token in re.split(r"[\s,;]+", PAREN_RE.sub(" ", text)):
        if token and token not in ("and", "to", "&") and not re.fullmatch(ID, token):
            return False
    return True


def only_list_glue(text: str) -> bool:
    """Between two ids of one list: separators and the words that join them."""
    return all(t in ("", "and", "to", "or", "&") for t in re.split(r"[\s,;]+", text))


def is_skipped(rel: Path) -> bool:
    folders = rel.parts[:-1]
    return any(p in SKIPPED_DIRS or p.startswith(".") for p in folders) or rel.name.startswith(".")


